export function serializeCampaign(c) {
  if (!c) return null;
  return {
    id: c.id,
    orgId: c.orgId,
    name: c.name,
    category: c.category,
    status: c.status,
    groupId: c.groupId,
    groupName: c.group?.name,
    recordingId: c.recordingId,
    recordingName: c.recording?.name,
    recordingDurationSec: c.recording?.durationSec,
    scheduledAt: c.scheduledAt,
    optOutEnabled: c.optOutEnabled,
    concurrency: c.concurrency,
    creditsPerCall: c.creditsPerCall,
    recipients: c.recipients,
    processed: c.processed,
    answered: c.answered,
    played: c.played,
    unanswered: c.unanswered,
    busy: c.busy,
    failed: c.failed,
    skipped: c.skipped,
    optOuts: c.optOuts,
    creditsReserved: c.creditsReserved,
    creditsUsed: c.creditsUsed,
    requiresApproval: c.requiresApproval,
    approvedAt: c.approvedAt,
    rejectedReason: c.rejectedReason,
    startedAt: c.startedAt,
    completedAt: c.completedAt,
    createdAt: c.createdAt,
  };
}
